import os
import json
import PyPDF2
import traceback

def read_file(file):
    if file.name.endswith(".pdf"):
        try:
            pdf_reader = PyPDF2.PdfReader(file)
            text = ""
            for page in pdf_reader.pages:
                extracted = page.extract_text()
                if extracted:
                    text += extracted
            return text
        except Exception as e:
            raise Exception(f"error reading the PDF file: {e}")

    elif file.name.endswith(".txt"):
        return file.read().decode("utf-8")

    else:
        raise Exception(
            "unsupported file format only pdf and text file suppoted"
        )

import html

def parse_quiz_items(quiz_input):
    try:
        if isinstance(quiz_input, dict):
            quiz_dict = quiz_input
        else:
            quiz_dict = json.loads(quiz_input)

        items = []
        for key, value in quiz_dict.items():
            mcq = value.get("mcq", "")
            raw_opts = value.get("options", {})
            options = [(opt_key, opt_val) for opt_key, opt_val in raw_opts.items()]
            correct = value.get("correct", "")
            items.append({"question": mcq, "options": options, "correct": correct})
        return items
    except Exception as e:
        traceback.print_exception(type(e), e, e.__traceback__)
        return []

def render_mcqs_html(quiz_items, show_answers=False):
    cards = []
    for idx, item in enumerate(quiz_items, start=1):
        q_text = html.escape(str(item.get("question", "")))
        correct_val = html.escape(str(item.get("correct", "")))
        options_html = []
        for opt_key, opt_text in item.get("options", []):
            escaped_key = html.escape(str(opt_key).upper())
            escaped_val = html.escape(str(opt_text))
            options_html.append(
                f'<div class="mcq-option"><span class="mcq-opt-key">{escaped_key}</span> <span class="mcq-opt-val">{escaped_val}</span></div>'
            )
        opts_str = "\n".join(options_html)
        answer_badge = f'<div class="mcq-correct-badge">✓ Correct Answer: {correct_val}</div>' if show_answers else ""
        cards.append(f'''<div class="mcq-card">
            <div class="mcq-header">
                <div class="mcq-title-row">
                    <span class="mcq-qnum">Q{idx}</span>
                    <span class="mcq-qtext">{q_text}</span>
                </div>
                {answer_badge}
            </div>
            <div class="mcq-options-grid">{opts_str}</div>
        </div>''')
    return "\n".join(cards)

import io, zipfile, xml.sax.saxutils

def generate_mcqs_docx(quiz_items, subject="General", tone="Standard"):
    sep_d = "=" * 68
    lines = [sep_d, "QUIZ ASSESSMENT REPORT", f"Subject: {subject or 'General'} | Complexity: {tone or 'Standard'}", f"Total Questions: {len(quiz_items)} | Generated by MCQGen", sep_d, "", "SECTION I: QUESTIONS", ""]
    ans_keys = []
    for idx, item in enumerate(quiz_items, start=1):
        lines.append(f"{idx}. {str(item.get('question', '')).strip()}")
        raw_c = str(item.get("correct", "")).strip()
        cor = ""
        for opt_k, opt_v in item.get("options", []):
            k, v = str(opt_k).strip().upper(), str(opt_v).strip()
            lines.append(f"   {k}) {v}")
            if raw_c.upper() == k or raw_c.lower() == v.lower():
                cor = k
        ans_keys.append(f"Q{idx}: {cor or (raw_c[0].upper() if raw_c else '')}")
        lines.append("")
    lines.extend(["-" * 68, "", "ANSWER KEY", ""] + ans_keys + ["", sep_d])
    b_xml = "".join(f'<w:p><w:r><w:t xml:space="preserve">{xml.sax.saxutils.escape(ln)}</w:t></w:r></w:p>' for ln in lines)
    doc_xml = f'<?xml version="1.0" encoding="UTF-8" standalone="yes"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>{b_xml}<w:sectPr/></w:body></w:document>'
    ct_xml = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>'
    rels_xml = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>'
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", ct_xml)
        z.writestr("_rels/.rels", rels_xml)
        z.writestr("word/document.xml", doc_xml)
    return buf.getvalue()

def get_table_data(quiz_str):
    try:
        # convert the quiz from a str to dict
        quiz_dict = json.loads(quiz_str)
        quiz_table_data = []

        # iterate over the quiz dictionary and extract the required information
        for key, value in quiz_dict.items():
            mcq = value["mcq"]
            options = " || ".join(
                [
                    f"{option}-> {option_value}" for option, option_value in value["options"].items()
                ]
            )

            correct = value["correct"]
            quiz_table_data.append({"MCQ": mcq, "Choices": options, "Correct": correct})

        return quiz_table_data

    except Exception as e:
        traceback.print_exception(type(e), e, e.__traceback__)
        return False
